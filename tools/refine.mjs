import fs from 'node:fs';
let html = fs.readFileSync('index.html', 'utf8');
html = html.replace(/<span class="(?:hero-number|tab-index|step-number)">[^<]*<\/span>/g, '');
html = html.replace(/<span>0[1-6]<\/span>/g, '');
html = html.replace(/0[1-6] \/ /g, '');
html = html.replace('src="./assets/madalin-stage.jpg" alt="Mădălin Nuică, medaliat la Romanian International Grand Prix" loading="lazy" width="700" height="855"', 'src="./assets/madalin-training.jpg" alt="Mădălin Nuică pe scena Romanian International Grand Prix, cu medalia de competiție" loading="lazy" width="640" height="427"');
html = html.replace(/<span class="tab-subtitle">[^<]*<\/span>/g, '');
const start = html.indexOf('      <div class="program-content reveal">');
const end = html.indexOf('      </div></div>', start);
if (start < 0 || end < 0) throw new Error('Program section not found');
let program = html.slice(start, end);
const photo = program.match(/        <div class="program-photo">.*<\/div>\r?\n/);
if (!photo) throw new Error('Program image not found');
program = program.replace(photo[0], '');
program = program.replace('<div class="program-content reveal">', '<div class="program-content reveal">\n        <div class="program-photo"><img src="./assets/gym.jpg" alt="Greutăți și echipamente de fitness, imagine de atmosferă" loading="lazy" width="1800" height="1200"><small>FIECARE ANTRENAMENT CONTEAZĂ.</small></div>');
program = program.replace(/<span class="panel-category">[^<]*<\/span>/g, '');
program = program.replace(/<h3>(.*?)<\/h3>/g, (_, title) => '<h3>' + title.replaceAll('<br>', ' ') + '</h3>');
program = program.replace(/VORBIM DESPRE (?:OBIECTIVUL|PRIMUL) MEU(?: PAS)?/g, 'DISCUTĂ CU MĂDĂLIN');
html = html.slice(0, start) + program + html.slice(end);
fs.writeFileSync('index.html', html);
